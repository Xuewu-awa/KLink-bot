"""Generate small rule tables directly from the current parsed pak/runtime schema.

Usage: python gen-live-rule-tables.py <kards-install-review> <output.cs>
The combination order is significant: a seeded random index selects a row entry.
"""
import argparse
import hashlib
import json
from pathlib import Path


def generate(root, enum_values_path):
    table_path = root / "parsed/kards/Content/Structs/kreditCombinationsUSUnits.table.json"
    enum_path = root / "parsed/kards/Content/Structs/CardMoveReason.metadata.json"
    schema_path = root / "native-schema-reference.json"
    table = json.loads(table_path.read_text(encoding="utf-8"))["kreditCombinationsUSUnits"]
    enum_export = json.loads(enum_path.read_text(encoding="utf-8"))["exports"][0]
    move_names = next(p for p in enum_export["data"] if p["Name"] == "DisplayNameMap")["Value"]
    enum_values = json.loads(enum_values_path.read_text(encoding="utf-8"))["names"]
    display_names = {pair[0]["Value"]: pair[1]["CultureInvariantString"] for pair in move_names}
    move_entries = [e for e in enum_values if not e["name"].endswith("_MAX")]
    assert [e["value"] for e in move_entries] == list(range(len(move_entries)))
    schema = json.loads(schema_path.read_text(encoding="utf-8"))["objects"]
    enums = {
        "/Script/kards.ESideEnum": [n.split("::")[-1] for n, value in schema["/Script/kards.ESideEnum"]["names"] if not n.endswith("_MAX")],
        "/Script/kards.ECardLocationEnum": [n.split("::")[-1] for n, value in schema["/Script/kards.ECardLocationEnum"]["names"] if not n.endswith("_MAX")],
        "/Game/Structs/CardMoveReason.CardMoveReason": [display_names[e["name"].split("::")[-1]] for e in move_entries],
        # EFactionEnum is the same ABI used by the current card CDO faction fields.
        "/Script/KardsCore.EFactionEnum": ["NotAvailable", "Germany", "Britain", "Japan", "Soviet", "USA", "France", "Italy", "Poland", "Finland", "Anzac", "Allies", "Neutral"],
    }
    for key in ["/Script/kards.ESideEnum", "/Script/kards.ECardLocationEnum"]:
        assert [v for n, v in schema[key]["names"] if not n.endswith("_MAX")] == list(range(len(enums[key])))
    assert [p[0]["Value"] for p in move_names] == [f"NewEnumerator{i}" for i in range(14)]
    field = next(iter(table["rows"].values()))["Value"][0]["Name"]
    lines = ["// <auto-generated>", "// gen-live-rule-tables.py; sources from the current pak and read-only runtime schema."]
    for path in [table_path, enum_path, schema_path, enum_values_path]:
        lines.append(f"// {path.name}: SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}")
    lines += ["// </auto-generated>", "#nullable enable", "namespace KLink.Bot.Effects.Blueprint;", "", "internal static class LiveRuleTables", "{", "    private static readonly Dictionary<string, double[][]> KreditCombos = new(StringComparer.Ordinal)", "    {"]
    for key, row in table["rows"].items():
        assert row["Value"][0]["Name"] == field
        combos = []
        for item in row["Value"][0]["Value"]:
            vector = item["Value"][0]["Value"]
            combos.append("[" + ", ".join(str(float(vector[a])) + "d" for a in "XYZ") + "]")
        lines.append(f'        ["{key}"] = [' + ", ".join(combos) + "],")
    lines += ["    };", "", "    private static readonly Dictionary<string, string[]> EnumNames = new(StringComparer.Ordinal)", "    {"]
    for key, names in enums.items():
        lines.append(f'        ["{key}"] = [' + ", ".join(json.dumps(n) for n in names) + "],")
    lines += ["    };", "", "    public static bool TryGetEnumName(string enumPath, int value, out string name)", "    {", "        name = \"\";", "        if (!EnumNames.TryGetValue(enumPath, out var names) || value < 0 || value >= names.Length) return false;", "        name = names[value];", "        return true;", "    }", "", "    public static bool TryGetRow(string tablePath, string rowName, out object? row)", "    {", "        row = null;", '        if (tablePath != "/Game/Structs/kreditCombinationsUSUnits.kreditCombinationsUSUnits"', "            || !KreditCombos.TryGetValue(rowName, out var combos)) return false;", "        // The Blueprint receives a writable row copy, never the process-wide table.", "        row = new Dictionary<string, object?>", "        {", f'            ["{field}"] = combos.Select(v => (object?)v.Cast<object?>().ToList()).ToList(),', "        };", "        return true;", "    }", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--enum-values", type=Path, required=True,
                        help="LiveEnumProbe output containing serialized enum names/value pairs")
    args = parser.parse_args()
    args.output.write_text(generate(args.source, args.enum_values), encoding="utf-8")
    print(args.output)
